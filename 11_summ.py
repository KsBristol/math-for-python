"""
В клетки таблицы 3 на 3 вписали девять различных натуральных чисел. Затем выписали суммы пар чисел, 
стоящих в соседних клетках.(Клетки считаются соседними, если имеют общую сторону.) Оказалось, что 
среди этих сумм найдется 11 последовательных чисел. приведите пример такой расстановки чисел.
"""

from itertools import permutations

def has_11_consecutive(numbers):
    """
    Проверяет, есть ли в множестве numbers 11 последовательных чисел
    """
    unique = sorted(set(numbers))
    # Проходим окном длиной 11 по отсортированному списку
    for i in range(len(unique) - 10):
        # Если разница между последним и первым элементом окна равна 10,
        # значит все 11 чисел последовательны
        if unique[i + 10] == unique[i] + 10:
            return True
    return False

def find_arrangement():
    """
    Ищет расстановку 9 различных натуральных чисел в таблице 3x3,
    где среди сумм соседних клеток есть 11 последовательных чисел
    """
    # Начинаем с чисел от 1 до 9, можно расширить диапазон если не найдется
    numbers = list(range(1, 10))
    
    # Перебираем все перестановки 9 чисел
    for perm in permutations(numbers):
        # Размещаем перестановку в таблице 3x3
        a, b, c, d, e, f, g, h, i = perm
        
        # Вычисляем 12 сумм соседних клеток
        sums = [
            # Горизонтальные соседи
            a + b, b + c,     # первая строка
            d + e, e + f,     # вторая строка  
            g + h, h + i,     # третья строка
            # Вертикальные соседи
            a + d, d + g,     # первый столбец
            b + e, e + h,     # второй столбец
            c + f, f + i      # третий столбец
        ]
        
        # Проверяем, есть ли 11 последовательных чисел среди сумм
        if has_11_consecutive(sums):
            print("Найдена расстановка:")
            print(f"{a} {b} {c}")
            print(f"{d} {e} {f}") 
            print(f"{g} {h} {i}")
            print("\nСуммы соседних клеток:", sums)
            print("Уникальные суммы (отсорт.):", sorted(set(sums)))
            return perm
    
    print("Решение не найдено для чисел 1-9. Попробуйте расширить диапазон.")
    return None

# Расширенная версия с возможностью задать диапазон чисел
def find_arrangement_extended(start=1, end=9):
    """
    Ищет расстановку в указанном диапазоне чисел
    """
    from itertools import permutations
    
    numbers = list(range(start, end + 1))
    print(f"Перебираем расстановки чисел от {start} до {end}...")
    
    count = 0
    for perm in permutations(numbers):
        count += 1
        if count % 100000 == 0:
            print(f"Проверено {count} расстановок...")
        
        a, b, c, d, e, f, g, h, i = perm
        
        sums = [
            a + b, b + c, d + e, e + f, g + h, h + i,
            a + d, d + g, b + e, e + h, c + f, f + i
        ]
        
        if has_11_consecutive(sums):
            print(f"\nНайдена расстановка (проверено {count} вариантов):")
            print(f"{a} {b} {c}")
            print(f"{d} {e} {f}") 
            print(f"{g} {h} {i}")
            print("\nСуммы соседних клеток:", sums)
            print("Уникальные суммы (отсорт.):", sorted(set(sums)))
            
            # Покажем какие именно 11 последовательных чисел найдены
            unique = sorted(set(sums))
            for i in range(len(unique) - 10):
                if unique[i + 10] == unique[i] + 10:
                    print(f"11 последовательных чисел: {list(range(unique[i], unique[i] + 11))}")
                    break
            
            return perm
    
    print(f"Решение не найдено для чисел от {start} до {end}")
    return None

